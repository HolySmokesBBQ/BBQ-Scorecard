// Board Tier B (docs/superpowers/specs/2026-09-29-board-ocr-size-design.md):
// the SHA-256 of every OCR file Android fetches at runtime is a constant
// compiled into the app, never fetched (a hash served by the server it is
// meant to check proves nothing). This script computes them from the files
// we hand to Website to serve (public/tesseract/) and writes
// src/board/ocrHashes.js.
//
//   node scripts/gen-ocr-hashes.mjs           write the constants
//   node scripts/gen-ocr-hashes.mjs --check   exit 1 if they're stale
//
// It also proves the three cores are byte-identical to the pinned
// tesseract.js-core package, so the version in the URL path is the truth.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(ROOT, 'src/board/ocrHashes.js');

export const OCR_CORE_FILES = [
  'tesseract-core-relaxedsimd-lstm.wasm.js',
  'tesseract-core-simd-lstm.wasm.js',
  'tesseract-core-lstm.wasm.js',
];
export const OCR_REMOTE_FILES = [...OCR_CORE_FILES, 'eng.traineddata'];

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

export function computeOcrHashes(root = ROOT) {
  const version = JSON.parse(readFileSync(resolve(root, 'node_modules/tesseract.js-core/package.json'), 'utf8')).version;
  const hashes = {};
  for (const f of OCR_REMOTE_FILES) {
    const bytes = readFileSync(resolve(root, 'public/tesseract', f));
    hashes[f] = sha256(bytes);
    if (OCR_CORE_FILES.includes(f)) {
      const pinned = readFileSync(resolve(root, 'node_modules/tesseract.js-core', f));
      if (sha256(pinned) !== hashes[f]) {
        throw new Error(`public/tesseract/${f} differs from tesseract.js-core ${version}`);
      }
    }
  }
  return { version, hashes };
}

export function renderHashesModule({ version, hashes }) {
  const lines = OCR_REMOTE_FILES.map((f) => `  '${f}': '${hashes[f]}',`);
  return [
    '// GENERATED by scripts/gen-ocr-hashes.mjs from public/tesseract/. Do not edit.',
    '// Run `node scripts/gen-ocr-hashes.mjs` after changing any OCR file; the test',
    '// suite fails while these are stale.',
    '',
    `export const OCR_VERSION = '${version}';`,
    '',
    'export const OCR_HASHES = Object.freeze({',
    ...lines,
    '});',
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = renderHashesModule(computeOcrHashes());
  if (process.argv.includes('--check')) {
    const have = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== want) {
      console.error('src/board/ocrHashes.js is stale. Run: node scripts/gen-ocr-hashes.mjs');
      process.exit(1);
    }
    console.log('OCR hashes are current.');
  } else {
    writeFileSync(OUT, want);
    console.log(`wrote ${OUT}`);
  }
}
